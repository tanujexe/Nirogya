import { motion, AnimatePresence } from 'motion/react';
import { X, Bot, Activity, AlertTriangle, Stethoscope, CheckCircle2 } from 'lucide-react';

export default function SummaryModal({ isOpen, onClose, summary }) {
  if (!isOpen || !summary) return null;

  const severityColor = {
    'Low': 'text-green-500 bg-green-500/10',
    'Medium': 'text-yellow-500 bg-yellow-500/10',
    'High': 'text-red-500 bg-red-500/10',
    'Unknown': 'text-gray-500 bg-gray-500/10'
  }[summary.severityLevel] || 'text-blue-500 bg-blue-500/10';

  return (
    <AnimatePresence>
      <motion.div
        initial={{ opacity: 0 }}
        animate={{ opacity: 1 }}
        exit={{ opacity: 0 }}
        className="fixed inset-0 z-[100] flex items-center justify-center p-4 bg-black/60 backdrop-blur-sm"
        onClick={onClose}
      >
        <motion.div
          initial={{ opacity: 0, scale: 0.95, y: 20 }}
          animate={{ opacity: 1, scale: 1, y: 0 }}
          exit={{ opacity: 0, scale: 0.95, y: 20 }}
          onClick={(e) => e.stopPropagation()}
          className="bg-card w-full max-w-2xl max-h-[90vh] overflow-y-auto rounded-3xl shadow-2xl border border-border flex flex-col no-scrollbar"
        >
          {/* Header */}
          <div className="sticky top-0 z-10 bg-card/90 backdrop-blur-xl border-b border-border p-6 flex justify-between items-center">
            <div className="flex items-center gap-3">
              <div className="p-3 bg-gradient-to-br from-[var(--healthcare-cyan)] to-[var(--healthcare-blue)] rounded-xl shadow-lg">
                <Bot className="w-6 h-6 text-white" />
              </div>
              <div>
                <h2 className="text-2xl font-black">AI Summary</h2>
                <p className="text-sm text-muted-foreground">Generated by Healthcare AI</p>
              </div>
            </div>
            <button
              onClick={onClose}
              className="p-2 rounded-xl hover:bg-muted text-muted-foreground transition-colors"
            >
              <X className="w-6 h-6" />
            </button>
          </div>

          {/* Content */}
          <div className="p-6 space-y-8">
            {/* Severity & Specialist */}
            <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
              <div className="p-5 rounded-2xl border border-border bg-muted/30 flex items-center gap-4">
                <div className={`p-3 rounded-xl ${severityColor}`}>
                  <Activity className="w-6 h-6" />
                </div>
                <div>
                  <p className="text-sm text-muted-foreground font-medium mb-1">Severity Level</p>
                  <p className="font-bold text-lg">{summary.severityLevel || 'Not Specified'}</p>
                </div>
              </div>

              <div className="p-5 rounded-2xl border border-border bg-muted/30 flex items-center gap-4">
                <div className="p-3 rounded-xl text-[var(--healthcare-cyan)] bg-[var(--healthcare-cyan)]/10">
                  <Stethoscope className="w-6 h-6" />
                </div>
                <div>
                  <p className="text-sm text-muted-foreground font-medium mb-1">Suggested Specialist</p>
                  <p className="font-bold text-lg">{summary.suggestedSpecialist || 'General Physician'}</p>
                </div>
              </div>
            </div>

            {/* Explanation */}
            <div>
              <h3 className="text-lg font-bold flex items-center gap-2 mb-4">
                <CheckCircle2 className="w-5 h-5 text-[var(--healthcare-cyan)]" />
                Simple Explanation
              </h3>
              <div className="p-5 rounded-2xl bg-[var(--healthcare-cyan)]/5 border border-[var(--healthcare-cyan)]/20 text-[var(--healthcare-blue)] dark:text-gray-200 leading-relaxed">
                {summary.explanation}
              </div>
            </div>

            {/* Key Findings */}
            {summary.keyFindings && summary.keyFindings.length > 0 && (
              <div>
                <h3 className="text-lg font-bold flex items-center gap-2 mb-4">
                  <Activity className="w-5 h-5 text-blue-500" />
                  Key Findings
                </h3>
                <ul className="space-y-3">
                  {summary.keyFindings.map((finding, idx) => (
                    <li key={idx} className="flex items-start gap-3 p-3 rounded-xl hover:bg-muted/50 transition-colors">
                      <div className="w-2 h-2 mt-2 rounded-full bg-blue-500 shrink-0" />
                      <span className="text-foreground/90">{finding}</span>
                    </li>
                  ))}
                </ul>
              </div>
            )}

            {/* Abnormal Values */}
            {summary.abnormalValues && summary.abnormalValues.length > 0 && (
              <div>
                <h3 className="text-lg font-bold flex items-center gap-2 mb-4 text-red-500">
                  <AlertTriangle className="w-5 h-5" />
                  Abnormal Values
                </h3>
                <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
                  {summary.abnormalValues.map((val, idx) => (
                    <div key={idx} className="p-3 rounded-xl bg-red-500/5 border border-red-500/20 text-red-600 dark:text-red-400 font-medium flex items-center gap-2">
                      <div className="w-1.5 h-1.5 rounded-full bg-red-500" />
                      {val}
                    </div>
                  ))}
                </div>
              </div>
            )}
          </div>
          
          {/* Footer */}
          <div className="p-6 border-t border-border bg-muted/10 text-xs text-muted-foreground text-center">
            <p>Disclaimer: This summary is generated by AI and is for educational purposes only. It is not a substitute for professional medical advice, diagnosis, or treatment.</p>
          </div>
        </motion.div>
      </motion.div>
    </AnimatePresence>
  );
}
